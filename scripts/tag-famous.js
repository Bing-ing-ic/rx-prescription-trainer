function loadJson(f) { return JSON.parse(fs.readFileSync(f, 'utf8')); }

function main() {
  const dry = process.argv.includes('--dry');
  const famous = loadJson(FAMOUS);
  const tagDef = loadJson(TAGS);

  // 别名 → 标准词 索引（label 与 aliases 都指向标准 label）
  const aliasIndex = (def) => {
    const m = new Map();
    def.forEach(x => { m.set(x.label, x.label); (x.aliases || []).forEach(a => m.set(a, x.label)); });
    return m;
  };
  const idx = {
    syndromes: aliasIndex(tagDef.syndromes),
    organs: aliasIndex(tagDef.organs),
    symptoms: aliasIndex(tagDef.symptoms),
    kyo_jitsu: aliasIndex(tagDef.kyo_jitsu),
    ki_ketsu_sui: aliasIndex(tagDef.ki_ketsu_sui),
    six_channel: aliasIndex(tagDef.six_channel),
    fukushin: aliasIndex(tagDef.fukushin)
  };
  // 治法 treatments 为宽松标签，不做受控词表校验。

  const report = { missingMap: [], invalid: [], total: 0, tagged: 0 };
  for (const p of famous.prescriptions) {
    report.total++;
    const m = MAP[p.id];
    if (!m) { report.missingMap.push(p.id); continue; }
    const normList = (arr, map, key) => {
      const out = [];
      arr.forEach(v => { const s = map.get(v); if (s) out.push(s); else { out.push(v); report.invalid.push(`${p.id}.${key}=${v}`); } });
      return out;
    };
    const normScalar = (v, map, key) => { if (!v) return ''; const s = map.get(v); if (!s) report.invalid.push(`${p.id}.${key}=${v}`); return s || v; };
    const tags = {
      syndromes: normList(m.sy.filter(Boolean), idx.syndromes, 'syndromes'),
      organs: normList(m.organ.filter(Boolean), idx.organs, 'organs'),
      treatments: m.tr.filter(Boolean),
      target_symptoms: normList(m.tgt.filter(Boolean), idx.symptoms, 'target_symptoms'),
      symptoms: normList(m.tgt.filter(Boolean), idx.symptoms, 'symptoms'),
      kyo_jitsu: normScalar(m.kj, idx.kyo_jitsu, 'kyo_jitsu'),
      ki_ketsu_sui: normList(m.kk.filter(Boolean), idx.ki_ketsu_sui, 'ki_ketsu_sui'),
      six_channel: normScalar(m.sc, idx.six_channel, 'six_channel'),
      fukushin: normScalar(m.fk, idx.fukushin, 'fukushin'),
      tongue: '',
      pulse: ''
    };

    p.tags = tags;
    report.tagged++;
  }

  console.log(`总数 ${report.total}，已打标 ${report.tagged}`);
  if (report.missingMap.length) console.log('缺映射: ' + report.missingMap.join(', '));
  if (report.invalid.length) { console.log('未命中词表:'); report.invalid.forEach(x => console.log('  ✗ ' + x)); }

  if (!dry && !report.missingMap.length && !report.invalid.length) {
    famous.version = '2026.11.25-famous-r6';
    fs.writeFileSync(FAMOUS, JSON.stringify(famous, null, 2) + '\n', 'utf8');
    console.log('已回写 tcm-famous-prescriptions.json');
  } else if (dry) {
    console.log('[dry] 未回写');
  } else {
    console.log('存在问题，未回写。');
    process.exitCode = 1;
  }
}

main();
